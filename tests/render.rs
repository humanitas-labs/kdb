#[test]
fn blocked_by_column_and_frontmatter() {
    let ws = TestWorkspace::new();
    let conn = seed(&ws);
    let p = add_project(&conn, "kdb", "KDB", "projects/kdb", None);
    let s = add_space(&conn, "labs", "THR", "labs", "Lab");
    let a = add_task(&conn, Ok(p), 1, "a", "backlog", 3);
    let b = add_task(&conn, Ok(p), 2, "b", "parked", 3);
    let c = add_task(&conn, Ok(p), 3, "c", "done", 3);
    let d = add_task(&conn, Err(s), 7, "d", "today", 3);
    let child = add_child(&conn, p, a, 1, "child of a");
    let grandchild = add_child(&conn, p, child, 1, "grandchild");
    // a is blocked by an open, a parked, a done, and a cross-space task.
    for on in [d, c, b] {
        block(&conn, a, on);
    }
    block(&conn, grandchild, b);
    // A closed dependent is never blocked.
    block(&conn, c, d);

    assert!(ws.kdb(&["render", "-P", "kdb"]).status.success());
    let index = ws.read("projects/kdb/.tasks/index.md");
    assert!(index.contains("| [KDB-0001](T-0001.md) | a | KDB-0002, THR-0007 | 3 |\n"), "{index}");
    let task = ws.read("projects/kdb/.tasks/T-0001.md");
    assert!(task.starts_with("---\nblocked_by:\n  - KDB-0002\n  - THR-0007\n---\n# KDB-0001 — a\n\n"), "{task}");
    // Blockedness inherits down the parent chain; own edges come first, deduped.
    assert!(task.contains("| `KDB-0001.1` | child of a | KDB-0002, THR-0007 | 3 |\n"), "{task}");
    assert!(task.contains("| `KDB-0001.1.1` | grandchild | KDB-0002, THR-0007 | 3 |\n"), "{task}");

    // Resolving the blockers clears the column and the frontmatter.
    conn.execute("UPDATE tasks SET status = 'done' WHERE id IN (?1, ?2)", params![b, d]).unwrap();
    assert!(ws.kdb(&["render", "-P", "kdb"]).status.success());
    assert!(ws.read("projects/kdb/.tasks/index.md").contains("| [KDB-0001](T-0001.md) | a |  | 3 |\n"));
    assert!(ws.read("projects/kdb/.tasks/T-0001.md").starts_with("# KDB-0001 — a\n"));
}

#[test]
fn space_board_merges_owners_and_links_relatively() {
    let ws = TestWorkspace::new();
    let conn = seed(&ws);
    let space = add_space(&conn, "iceberg", "ICE", "labs", "Iceberg Labs");
    let adrata = add_project(&conn, "adrata", "ADR", "labs/clients/adrata", Some(space));
    add_task(&conn, Err(space), 1, "Ship site", "in_progress", 1);
    add_task(&conn, Ok(adrata), 1, "Data model", "in_progress", 3);
    add_task(&conn, Ok(adrata), 2, "Later", "backlog", 3);

    let out = ws.kdb(&["render", "-S", "iceberg"]);
    assert!(out.status.success(), "{}", stderr(&out));
    assert!(stdout(&out).ends_with("labs/.tasks/index.md\n"));
    let body = ws.read("labs/.tasks/index.md");
    assert!(body.starts_with("# Iceberg Labs — Tasks\n\n"));
    assert!(body.contains("## ![](../../.kdb/icons/in_progress.h.svg) In Progress (2)\n\n_Actively being worked on right now._\n\n| | Task | Project | Title | Blocked by | Priority |\n|---|---|---|---|---|---|\n"));
    assert!(body.contains("| ![](../../.kdb/icons/in_progress.svg) | [ICE-0001](T-0001.md) | iceberg | Ship site |  | 1 |\n| ![](../../.kdb/icons/in_progress.svg) | [ADR-0001](../clients/adrata/.tasks/T-0001.md) | adrata | Data model |  | 3 |\n"));
    // Backlog collapses on the space board.
    assert!(body.contains("## ![](../../.kdb/icons/backlog.h.svg) Backlog (1)\n\n_Future work; not scheduled into a cycle yet._\n\n_`kdb tasks list -S iceberg -s backlog`_\n\n"));
    assert!(!body.contains("Later"));
    // Both task files exist where the links point; the member board was refreshed.
    assert!(ws.path("labs/.tasks/T-0001.md").exists());
    assert!(ws.path("labs/clients/adrata/.tasks/T-0001.md").exists());
    assert!(ws.path("labs/clients/adrata/.tasks/index.md").exists());
}

