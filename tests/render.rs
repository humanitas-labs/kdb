//! `kdb render -P | -S | --all` board materialization: v1 parity plus the
//! icon column (iss-0070) and the Blocked-by column (iss-0071).

mod common;

use common::{TestWorkspace, stderr, stdout};
use rusqlite::{Connection, params};

/// Migrate the db through the binary (a no-op `--all` render), then open it.
fn seed(ws: &TestWorkspace) -> Connection {
    let out = ws.kdb(&["render", "--all"]);
    assert!(out.status.success(), "{}", stderr(&out));
    Connection::open(ws.path(".kdb/index.db")).unwrap()
}

fn add_space(conn: &Connection, slug: &str, alias: &str, path: &str, name: &str) -> i64 {
    conn.execute(
        "INSERT INTO spaces (slug, name, alias, path) VALUES (?1, ?2, ?3, ?4)",
        params![slug, name, alias, path],
    )
    .unwrap();
    conn.last_insert_rowid()
}

fn add_project(conn: &Connection, slug: &str, alias: &str, path: &str, space: Option<i64>) -> i64 {
    conn.execute(
        "INSERT INTO projects (slug, alias, name, path, space_id) VALUES (?1, ?2, ?1, ?3, ?4)",
        params![slug, alias, path, space],
    )
    .unwrap();
    conn.last_insert_rowid()
}

/// Top-level task owned by a project (`Ok(id)`) or a space (`Err(id)`).
fn add_task(conn: &Connection, owner: Result<i64, i64>, seq: i64, title: &str, status: &str, pri: i64) -> i64 {
    let (project, space) = match owner {
        Ok(p) => (Some(p), None),
        Err(s) => (None, Some(s)),
    };
    conn.execute(
        "INSERT INTO tasks (project_id, space_id, seq, title, status, priority) VALUES (?1, ?2, ?3, ?4, ?5, ?6)",
        params![project, space, seq, title, status, pri],
    )
    .unwrap();
    conn.last_insert_rowid()
}

fn add_child(conn: &Connection, project: i64, parent: i64, child_seq: i64, title: &str) -> i64 {
    conn.execute(
        "INSERT INTO tasks (project_id, parent_id, child_seq, title) VALUES (?1, ?2, ?3, ?4)",
        params![project, parent, child_seq, title],
    )
    .unwrap();
    conn.last_insert_rowid()
}

fn block(conn: &Connection, task: i64, on: i64) {
    conn.execute("INSERT INTO task_deps (task_id, depends_on) VALUES (?1, ?2)", params![task, on]).unwrap();
}

#[test]
fn project_board_writes_index_and_task_files() {
    let ws = TestWorkspace::new();
    let conn = seed(&ws);
    let p = add_project(&conn, "kdb", "KDB", "projects/kdb", None);
    let id = add_task(&conn, Ok(p), 1, "first", "backlog", 1);
    conn.execute("UPDATE tasks SET body = '## Goal\n\nDo the thing.\n' WHERE id = ?1", [id]).unwrap();
    add_task(&conn, Ok(p), 2, "shipped", "done", 3);
    add_task(&conn, Ok(p), 3, "a | pipe", "in_progress", 2);

    let out = ws.kdb(&["render", "-P", "kdb"]);
    assert!(out.status.success(), "{}", stderr(&out));
    assert!(stdout(&out).ends_with("projects/kdb/.tasks/index.md\n"));

    let index = ws.read("projects/kdb/.tasks/index.md");
    assert!(index.starts_with("# kdb — Tasks\n\n_Generated by `kdb`. Do not edit by hand._\n\n## ![](../../../.kdb/icons/in_progress.h.svg) In Progress (1)\n\n_Actively being worked on right now._\n\n"));
    assert!(index.contains("| | Task | Title | Blocked by | Priority |\n|---|---|---|---|---|\n"));
    assert!(index.contains("| ![](../../../.kdb/icons/in_progress.svg) | [KDB-0003](T-0003.md) | a \\| pipe |  | 2 |\n"));
    assert!(index.contains("## ![](../../../.kdb/icons/backlog.h.svg) Backlog (1)\n\n_Future work; not scheduled into a cycle yet._\n\n| | Task"));
    assert!(index.contains("| ![](../../../.kdb/icons/backlog.svg) | [KDB-0001](T-0001.md) | first |  | 1 |\n"));
    // Hidden statuses collapse to a count and a command line.
    assert!(index.contains("## ![](../../../.kdb/icons/done.h.svg) Done (1)\n\n_Completed; outcome shipped or accepted._\n\n_`kdb tasks list -P kdb -s done`_\n\n"));
    assert!(index.ends_with("## Commands\n\n- `kdb tasks list -P kdb` — full list\n- `kdb tasks add \"title\" -P kdb` — add a task\n- `kdb tasks view <id>` — view a task\n"));

    let task = ws.read("projects/kdb/.tasks/T-0001.md");
    assert_eq!(task, "# KDB-0001 — first\n\n_Generated by `kdb`. Do not edit by hand._\n\n## Goal\n\nDo the thing.\n");
    assert!(ws.path("projects/kdb/.tasks/T-0003.md").exists());
    // Closed statuses get no files.
    assert!(!ws.path("projects/kdb/.tasks/T-0002.md").exists());

    // Icons are installed in the workspace root.
    for icon in ["backlog", "queued", "in_progress", "in_review", "done"] {
        assert!(ws.path(&format!(".kdb/icons/{icon}.svg")).exists(), "{icon}");
    }
}

